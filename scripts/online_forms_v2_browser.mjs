/** 只使用独占夹具的管理员和数据库，验证生产构建的桌面/手机完整流程。 */
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
const [workspace, evidence] = process.argv.slice(2)
const require = createRequire(resolve(workspace, 'package.json'))
const { chromium, devices, expect: baseExpect } = require('@playwright/test')
const expect = baseExpect.configure({timeout:20000})
const password = JSON.parse(readFileSync(resolve(evidence,'access.json'),'utf8')).password
const source = JSON.parse(readFileSync(new URL('../examples/online-forms-v2/travel-request.json',import.meta.url),'utf8'))
const browser = await chromium.launch({headless:true}), checks=[]
let passed=false
try {
  for (const [name,device] of [['desktop',devices['Desktop Chrome']],['mobile',devices['iPhone SE']]]) {
    const context = await browser.newContext({...device,baseURL:'http://127.0.0.1:18481'})
    await context.tracing.start({screenshots:true,snapshots:true})
    const page=await context.newPage(), errors=[]
    page.on('pageerror',error=>errors.push(String(error)))
    try {
      await page.goto('/login')
      await page.getByPlaceholder('用户名',{exact:true}).fill('admin')
      await page.getByPlaceholder('密码',{exact:true}).fill(password)
      await page.getByRole('button',{name:'登录',exact:true}).click()
      await expect(page).toHaveURL('http://127.0.0.1:18481/')
      const token=await page.evaluate(()=>localStorage.getItem('token'))
      const headers={Authorization:'Bearer '+token}
      async function get(path) {const response=await context.request.get('/api/v1/'+path,{headers});expect(response.status()).toBe(200);return (await response.json()).data}
      const code='travel-'+name
      await page.goto('/online-forms')
      await page.getByRole('button',{name:'新建草稿',exact:true}).click()
      const identity=page.locator('.identity input')
      await identity.nth(0).fill('出差申请 '+name)
      await identity.nth(1).fill(code)
      await page.getByRole('button',{name:'导入定义',exact:true}).click()
      await page.getByLabel('表单定义 JSON',{exact:true}).fill(JSON.stringify(source))
      await page.getByRole('button',{name:'校验并导入',exact:true}).click()
      await expect(page.getByRole('dialog')).not.toBeVisible()
      await page.getByRole('button',{name:'添加分组',exact:true}).click()
      await expect(page.locator('.section-row')).toHaveCount(3)
      await page.getByRole('button',{name:'删除分组',exact:true}).last().click()
      await expect(page.locator('.section-row')).toHaveCount(2)
      const rootFields=page.locator('.designer-fields').first()
      await rootFields.locator('.el-collapse-item__header').first().click()
      await page.getByLabel('字段标签',{exact:true}).first().fill('出差标题')
      await page.getByLabel('下移字段',{exact:true}).first().click()
      await rootFields.locator('.el-collapse-item__header').nth(1).click()
      await page.getByLabel('上移字段',{exact:true}).nth(1).click()
      await page.getByRole('button',{name:'服务端校验',exact:true}).click()
      await expect(page.getByRole('status').filter({hasText:'表单定义校验通过'})).toBeVisible()
      checks.push(name+': import/configure/groups/reorder/server-validation')

      await page.getByRole('tab',{name:'实时预览',exact:true}).click()
      await expect(page.getByLabel('护照号码',{exact:true})).not.toBeVisible()
      await page.getByRole('button',{name:'试填校验',exact:true}).click()
      await expect(page.locator('.el-form-item__error').filter({hasText:'必填字段不能为空'}).first()).toBeVisible()
      await page.getByLabel('出差标题',{exact:true}).fill('预览出差')
      await page.getByLabel('开始日期',{exact:true}).fill('2026-10-18')
      await page.getByLabel('开始日期',{exact:true}).press('Tab')
      await page.getByLabel('结束日期',{exact:true}).fill('2026-10-20')
      await page.getByLabel('结束日期',{exact:true}).press('Tab')
      await page.getByLabel('预算金额',{exact:true}).fill('100.00')
      await page.getByRole('button',{name:'添加明细',exact:true}).click()
      await page.getByLabel('费用项目',{exact:true}).fill('车费')
      await page.getByLabel('单价',{exact:true}).fill('0.10')
      await page.getByRole('button',{name:'试填校验',exact:true}).click()
      await expect(page.getByText('试填校验通过，未写入记录',{exact:true})).toBeVisible()
      expect((await get('online-forms/'+code+'/records/')).pagination.total).toBe(0)
      checks.push(name+': shared-preview/errors/details/precision/no-records')

      await page.getByRole('tab',{name:'表单配置',exact:true}).click()
      await page.getByRole('button',{name:'保存草稿',exact:true}).click()
      await expect(page.getByText('表单草稿已保存',{exact:true})).toBeVisible()
      await page.locator('.identity input').nth(0).fill('已发布出差 '+name)
      const publishResponse=page.waitForResponse(response=>new URL(response.url()).pathname.match(/^\/api\/v1\/online-forms\/forms\/[^/]+\/publish\/$/) && response.request().method()==='POST')
      await page.getByRole('button',{name:'发布',exact:true}).click()
      const published=await publishResponse
      if(!published.ok()) throw new Error(`publish failed (${published.status()}): ${(await published.text()).slice(0,500)}`)
      await expect(page.getByRole('link',{name:'打开填写页面',exact:true})).toBeVisible()
      const listed=await get('online-forms/forms/')
      const form=listed.items.find(item=>item.code===code)
      expect(form).toBeTruthy()
      expect(form.status).toBe('published');expect(form.name).toBe('已发布出差 '+name);expect(form.version).toBe(2)
      const exported=page.waitForEvent('download')
      await page.getByRole('button',{name:'导出定义',exact:true}).click()
      await (await exported).saveAs(resolve(evidence,name+'-definition.json'))
      await page.getByRole('button',{name:'复制为新草稿',exact:true}).click()
      await expect(page.locator('.identity input').nth(1)).toHaveValue('')
      await expect(page.getByRole('button',{name:'保存草稿',exact:true})).toBeEnabled()
      checks.push(name+': save-before-publish/immutable/export/copy')

      await page.goto('/online-forms/'+code)
      await expect(page.getByRole('heading',{name:'已发布出差 '+name,exact:true})).toBeVisible()
      await page.getByLabel('出差标题',{exact:true}).fill('正式出差')
      await page.locator('.el-switch').filter({has:page.getByLabel('境外出差',{exact:true})}).click()
      await page.getByLabel('护照号码',{exact:true}).fill('TEMP-PASSPORT')
      await page.locator('.el-switch').filter({has:page.getByLabel('境外出差',{exact:true})}).click()
      await expect(page.getByLabel('护照号码',{exact:true})).not.toBeVisible()
      await page.getByLabel('开始日期',{exact:true}).fill('2026-10-18')
      await page.getByLabel('开始日期',{exact:true}).press('Tab')
      await page.getByLabel('结束日期',{exact:true}).fill('2026-10-17')
      await page.getByLabel('结束日期',{exact:true}).press('Tab')
      await page.getByLabel('预算金额',{exact:true}).fill('1000.00')
      await expect(page.getByLabel('预算说明',{exact:true})).toBeVisible()
      await page.getByRole('button',{name:'添加明细',exact:true}).click()
      await page.getByLabel('费用项目',{exact:true}).fill('餐费')
      await page.getByLabel('单价',{exact:true}).fill('0.123')
      await page.getByRole('button',{name:'提交',exact:true}).click()
      await expect(page.locator('.el-form-item__error').filter({hasText:'开始日期不能晚于结束日期'})).toBeVisible()
      await expect(page.locator('.el-form-item__error').filter({hasText:'金额必须为精确十进制文本且符合精度限制'})).toBeVisible()
      await expect(page.getByLabel('出差标题',{exact:true})).toHaveValue('正式出差')
      expect((await get('online-forms/'+code+'/records/')).pagination.total).toBe(0)
      await page.getByLabel('结束日期',{exact:true}).fill('2026-10-20')
      await page.getByLabel('结束日期',{exact:true}).press('Tab')
      await page.getByLabel('预算说明',{exact:true}).fill('后续隐藏的说明')
      await page.getByLabel('预算金额',{exact:true}).fill('100.00')
      await expect(page.getByLabel('预算说明',{exact:true})).not.toBeVisible()
      await page.getByLabel('单价',{exact:true}).fill('0.10')
      await page.getByRole('button',{name:'添加明细',exact:true}).click()
      await page.getByRole('button',{name:'删除第 2 行',exact:true}).click()
      await page.screenshot({path:resolve(evidence,name+'-form.png'),fullPage:true})
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true)
      await page.getByRole('button',{name:'提交',exact:true}).click()
      await expect(page.getByRole('status').filter({hasText:'提交成功'})).toBeVisible()
      const records=await get('online-forms/'+code+'/records/')
      expect(records.pagination.total).toBe(1)
      const saved=records.items[0].data
      expect(saved.costs[0].amount).toBe('0.10');expect(saved.budget).toBe('100.00')
      expect(saved.passport).toBeUndefined();expect(saved.reason).toBeUndefined()
      expect(saved.international).toBe(false)
      expect(errors).toEqual([])
      checks.push(name+': runtime/conditional-required/comparison/nested-errors/hidden-stripping/submit/mobile-overflow')
      await context.tracing.stop()
    } catch(error) {
      await page.screenshot({path:resolve(evidence,name+'-failure.png'),fullPage:true}).catch(()=>{})
      await context.tracing.stop({path:resolve(evidence,name+'-failure.zip')}).catch(()=>{})
      throw error
    } finally {await context.close()}
  }
  passed=true
} finally {
  await browser.close()
  writeFileSync(resolve(evidence,'browser-report.json'),JSON.stringify({passed,checks},null,2))
}
