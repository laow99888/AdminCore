import { test, expect, type Page } from '@playwright/test'

const envelope = (data: unknown) => ({ code: 200, message: 'success', data })
const post = { id: 'post-one', code: 'editor', name: '编辑岗位', description: '内容编辑', order: 0, is_active: true, version: 1 }
const persons = Array.from({ length: 12 }, (_, i) => ({ id: `person-${i}`, username: `writer_${i}`, display_name: `编辑${i}`, department: 'dept', department_name: '编辑部门' }))
const paged = (items: unknown[], total = items.length, page = 1) => envelope({ items, pagination: { total, page, page_size: 10, total_pages: Math.ceil(total / 10) } })
async function settleDialogs(page: Page) {
  await expect(page.locator('.dialog-fade-enter-active, .dialog-fade-leave-active, .el-message-box-fade-enter-active, .el-message-box-fade-leave-active')).toHaveCount(0)
}
async function setup(page: Page, options: { member?: boolean; disabled?: boolean; english?: boolean; orgOff?: boolean } = {}) {
  await page.addInitScript(({ english }) => { localStorage.setItem('token', 'isolated-posts-fixture'); if (english) { localStorage.setItem('language', 'en-US'); localStorage.setItem('theme', 'dark') } }, options)
  await page.route('**/api/v1/**', route => {
    const url = new URL(route.request().url()), path = url.pathname
    if (path.endsWith('/auth/me/')) return route.fulfill({ json: envelope({ id: 'admin', username: 'admin', is_staff: !options.member, is_superuser: !options.member, permissions: ['*'] }) })
    if (path.endsWith('/modules/')) return route.fulfill({ json: envelope({ contract_version: 1, preset: 'standard', modules: [{ key: 'organization', title: '组织', paths: ['/organization'], enabled: !options.disabled && !options.orgOff, dependencies: [] }, { key: 'approvals', title: '审批', paths: ['/approvals'], enabled: true, dependencies: [] }] }) })
    if (path.endsWith('/brand/')) return route.fulfill({ json: envelope({ name: 'AdminCore' }) })
    if (path.endsWith('/menus/my_menu/')) return route.fulfill({ json: envelope([]) })
    if (path.endsWith('/posts/choices/')) return route.fulfill({ json: envelope([post]) })
    if (path.endsWith('/organization/posts/') && route.request().method() === 'GET') return route.fulfill({ json: paged([post]) })
    if (path.endsWith('/user-posts/')) return route.fulfill({ json: paged([]) })
    if (path.endsWith('/people/departments/') || path.endsWith('/assignee-departments/')) return route.fulfill({ json: envelope({ enabled: !options.orgOff, truncated: false, items: options.orgOff ? [] : [{ id: 'dept', name: '编辑部门', parent: null }] }) })
    if (path.endsWith('/people/') || path.endsWith('/assignees/')) {
      const current = Number(url.searchParams.get('page') || 1), search = url.searchParams.get('search') || ''
      const matching = persons.filter(person => person.username.includes(search) || person.display_name.includes(search))
      return route.fulfill({ json: paged(matching.slice((current - 1) * 10, current * 10), matching.length, current) })
    }
    if (path.endsWith('/approvals/')) return route.fulfill({ json: paged([]) })
    return route.fulfill({ json: envelope({ count: 0, totals: {}, login_trend: [], task_status: {} }) })
  })
}
async function openAssignee(page: Page) {
  await page.goto('/approvals')
  await page.getByRole('button', { name: '+ 发起申请', exact: true }).click()
  await page.getByRole('button', { name: '选择人员', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择人员', exact: true })
  await expect(picker.getByRole('radio').first()).toBeVisible()
  return picker
}

test('岗位表单验证与冲突保留输入，先比较再显式载入服务器字段', async ({ page }, info) => {
  await setup(page)
  await page.goto('/organization/posts')
  await expect(page.getByText('内容编辑', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑岗位', exact: true })
  await expect(dialog.getByRole('textbox', { name: '岗位编码', exact: true })).toBeDisabled()
  await dialog.getByRole('textbox', { name: '岗位名称', exact: true }).fill('保留我的修改')
  await page.route('**/organization/posts/post-one/', route => route.fulfill({ status: 409, json: envelope(null) }))
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('记录已被修改')
  await expect(dialog.getByRole('textbox', { name: '岗位名称', exact: true })).toHaveValue('保留我的修改')
  await page.route('**/organization/posts/post-one/', route => route.fulfill({ json: envelope({ ...post, version: 2 }) }))
  const panel = dialog.getByRole('region', { name: '编辑冲突' })
  await panel.getByRole('button', { name: '查看服务器最新值', exact: true }).click()
  await expect(panel.getByRole('table')).toContainText('编辑岗位')
  await expect(panel.getByRole('table')).toContainText('保留我的修改')
  await expect(dialog.getByRole('textbox', { name: '岗位名称', exact: true })).toHaveValue('保留我的修改')
  await panel.getByRole('button', { name: '载入服务器最新值（替换当前输入）', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: '岗位名称', exact: true })).toHaveValue('编辑岗位')
  await expect(page.locator('.el-overlay.is-message-box')).toHaveCount(0)
  await settleDialogs(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('post-form.png'), fullPage: true })
})

